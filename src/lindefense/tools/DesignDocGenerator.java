    private static String hitSummary(TowerStats s) {
        HitSpec h = s.hit;
        List<String> parts = new ArrayList<>();
        switch (s.kind) {
            case PROJECTILE: parts.add("projectile " + f(s.projectileSpeed) + " px/s" + (s.splashRadius > 0 ? ", splash " + f(s.splashRadius) : "")); break;
            case INSTANT: parts.add(s.pierce > 1 ? "beam through line" : "instant beam"); break;
            case CHAIN: parts.add("chain +" + s.chainHops + " hops within " + f(s.chainRange)); break;
            case PULSE: parts.add("pulse (all in range)"); break;
            case CUSTOM: parts.add("custom attack"); break;
            default: parts.add("support only"); break;
        }
        if (s.kind == AttackKind.INSTANT && s.chainHops > 0) parts.add("ricochet +" + s.chainHops + " within " + f(s.chainRange));
        if (s.hasUnlimitedRange()) parts.add("unlimited range");
        if (s.ignoresLos) parts.add("ignores line of sight");
        if (s.targets > 1) parts.add(s.targets + " targets");
        if (s.projectilesPerShot > 1) parts.add(s.projectilesPerShot + " shots");
        if (s.bounces > 0) parts.add(s.bounces + " bounces/" + f(s.bounceRange));
        if (s.clones > 0) parts.add("splits into " + s.clones);
        if (h.slowFraction > 0) parts.add("slow " + pct(h.slowFraction) + " " + f(h.slowDuration) + "s");
        if (h.knockback > 0) parts.add("knockback " + f(h.knockback));
        if (h.knockbackVsFast > 0) parts.add("knockback " + f(h.knockbackVsFast) + " vs fast");
        if (h.knockbackVsLead > 0) parts.add("knockback " + f(h.knockbackVsLead) + " vs Lead");
        if (h.armorBreak > 0) parts.add("armor crack " + f(h.armorBreakDuration) + "s");
        if (h.ignoresResistance) parts.add("hits Lead");
        if (h.markBonus > 0) parts.add("mark +" + pct(h.markBonus) + " " + f(h.markDuration) + "s");
        if (h.markFlat > 0) parts.add("mark +" + f(h.markFlat) + " " + f(h.markDuration) + "s");
        if (h.dotDps > 0) parts.add("burn " + f(h.dotDps) + "/s for " + f(h.dotDuration) + "s");
        if (h.multVsBoss != 1) parts.add("x" + f(h.multVsBoss) + " vs MOAB-class");
        if (h.flatVsBoss != 0) parts.add("+" + f(h.flatVsBoss) + " vs MOAB-class");
        if (h.multVsFortified != 1) parts.add("x" + f(h.multVsFortified) + " vs Fortified");
        if (h.flatVsFortified != 0) parts.add("+" + f(h.flatVsFortified) + " vs Fortified");
        if (h.flatVsLead != 0) parts.add("+" + f(h.flatVsLead) + " vs Lead");
        if (h.flatVsCeramic != 0) parts.add("+" + f(h.flatVsCeramic) + " vs Ceramic");
        if (h.multVsSortingAndLists != 1) parts.add("x" + f(h.multVsSortingAndLists) + " vs Sorting Algorithms / Linked Lists");
        if (h.multVsHighHp != 1) parts.add("x" + f(h.multVsHighHp) + " vs base HP >= 5");
        if (h.stripsCamoRegrow) parts.add("strips Camo/Regrow");
        if (s.seesCamo) parts.add("camo detection");
        if (s.auraRange > 0) {
            List<String> a = new ArrayList<>();
            if (s.auraRate > 0) a.add("+" + pct(s.auraRate) + " speed");
            if (s.auraDamage > 0) a.add("+" + f(s.auraDamage) + " damage");
            if (s.auraPierce > 0) a.add("+" + s.auraPierce + " pierce");
            if (s.auraRangeBonus > 0) a.add("+" + pct(s.auraRangeBonus) + " range");
            if (s.auraDetection) a.add("camo detection");
            if (s.auraSurveillanceImmunity) a.add("Surveillance immunity");
            parts.add("aura " + f(s.auraRange) + ": " + String.join(", ", a));
        }
        if (s.auraEnemySlow > 0) parts.add("field slow " + pct(s.auraEnemySlow) + (s.fieldRadius > 0 ? " r" + f(s.fieldRadius) : ""));
        if (s.fieldMarkFlat > 0) parts.add("field mark +" + f(s.fieldMarkFlat));
        if (s.fieldMarkPct > 0) parts.add("field mark +" + pct(s.fieldMarkPct));
        if (s.incomePerWave > 0) parts.add("income $" + f(s.incomePerWave) + "/round");
        return String.join("; ", parts);
    }

