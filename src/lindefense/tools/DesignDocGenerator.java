    /** Number of bodies produced by one enemy of this type including all descendants. */
    private static int bodies(EnemyType t) {
        int n = 1;
        for (int i = 0; i < t.getChildTypes().length; i++) n += t.getChildCounts()[i] * bodies(t.getChildTypes()[i]);
        return n;
    }

    private static String usedModifiers() {
        List<String> l = new ArrayList<>();
        for (Modifier m : Modifier.values()) {
            int first = -1;
            for (WaveDef d : WaveData.all()) for (SpawnGroup s : d.groups) if (s.modifiers.contains(m) && first < 0) first = d.number;
            l.add(m.label + " (first wave " + first + ")");
        }
        return String.join(", ", l);
    }
