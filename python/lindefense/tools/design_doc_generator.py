class DesignDocGenerator:
    """Generates DESIGN.md from the live data tables (tower catalog, enemy types,
wave data, maps) so the reference always matches what the code does.
Usage: .venv/bin/python -m lindefense.tools.design_doc_generator ../DESIGN.md   (from python/)."""
    def __init__(self):
        pass
    @staticmethod
    def main(args):
        out = _j.File((args[0] if (len(args) > 0) else 'DESIGN.md'))
        dd = Difficulty.parse((args[1] if (len(args) > 1) else _j.get_property('design.difficulty')))
        if dd is not None:
            DesignDocGenerator.table_mode = dd
        w = PrintWriter(out, 'UTF-8')
        try:
            DesignDocGenerator.write(w)
        finally:
            pass
        print(_j.s(_j.cat('Wrote ', out.get_absolute_path())))
    @staticmethod
    def f(v):
        if abs((v - _j.rint(v))) < 1e-9:
            return _j.s(_j.to_long(_j.rint(v)))
        return _j.replace_all(_j.replace_all(_j.format('%.2f', v), '0+$', ''), '\\.$', '')
    @staticmethod
    def pct(v):
        return _j.cat(_j.to_int(_j.jround((v * 100))), '%')
    @staticmethod
    def curve_text(points):
        """A waves.py (wave, scale) curve in words: '1.0 to wave 20, then 1.2 (w40), ... linear in between'."""
        f = DesignDocGenerator.f
        head = _j.cat(f(points[0][1]), ' to wave ', points[0][0])
        rest = ', '.join(_j.cat(f(v), ' (w', w0, ')') for w0, v in points[1:])
        return _j.cat(head, ', then ', rest, ', linear in between and continuing past the last point')
