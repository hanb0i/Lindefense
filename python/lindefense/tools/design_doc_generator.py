    @staticmethod
    def effects(list_):
        if len(list_) == 0:
            return '-'
        sb = _j.StringBuilder()
        for e in list_:
            if sb.length() > 0:
                sb.append('; ')
            sb.append(e.text)
        return sb.to_string()
