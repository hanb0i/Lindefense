    @staticmethod
    def bodies(t):
        """Number of bodies produced by one enemy of this type including all descendants."""
        n = 1
        i = 0
        while i < len(t.get_child_types()):
            n += (t.get_child_counts()[i] * DesignDocGenerator.bodies(t.get_child_types()[i]))
            i += 1
        return n
    @staticmethod
    def used_modifiers():
        l = _j.ArrayList()
        for m in Modifier.values():
            first = (-1)
            for d in waves.all_waves():
                for s in d.groups:
                    if (m in s.modifiers) and (first < 0):
                        first = d.number
            _j_add(l, _j.cat(m.label, ' (first wave ', first, ')'))
        return ', '.join(l)


